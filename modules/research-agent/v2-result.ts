import { z } from "zod";

const topic = z.enum([
  "growth",
  "pay",
  "hours",
  "benefits",
  "culture",
  "position",
  "company",
  "mental_space",
]);
const channel = z.enum([
  "disclosure",
  "credit",
  "recruitment_procurement",
  "community",
]);
const access = z.enum(["pdf", "html", "index_snippet"]);
const locator = z.object({
  physical_page: z.number().int().positive().nullable().optional(),
  printed_page: z.string().nullable().optional(),
  paragraph: z.number().int().positive().optional(),
  table: z.number().int().positive().optional(),
  row: z.number().int().positive().optional(),
  column: z.number().int().positive().optional(),
});
const fact = z.object({
  id: z.string(),
  evidence_id: z.string(),
  excerpt_id: z.string(),
  company_id: z.number().int().positive(),
  kind: z.enum(["normalized_fact", "source_claim"]),
  metric: z.string(),
  value: z.string().nullable(),
  quote: z.string().max(10000),
  locator,
  status: z.literal("source_claim"),
  scope: z.literal("company"),
  job_id: z.null(),
  period: z.string().nullable(),
  confidence: z.enum(["high", "medium", "low", "unknown"]),
  rule_version: z.string(),
  dimensions: z.array(topic),
  unit: z.string().optional(),
  currency: z.string().nullable().optional(),
  reporting_scope: z.string().optional(),
  normalized_value: z.string().optional(),
  polarity: z.string().optional(),
  conditional: z.boolean().optional(),
  department: z.string().nullable().optional(),
  role: z.string().nullable().optional(),
  risk_event: z
    .object({
      category: z.string(),
      subject: z.string().nullable(),
      date: z.string().nullable(),
      event_status: z.string(),
      amount_quote: z.string().nullable(),
      source_evidence_id: z.string(),
      limitation: z.string(),
    })
    .nullable()
    .optional(),
});
const translation = z.object({
  id: z.string(),
  fact_ids: z.array(z.string()).min(1),
  evidence_ids: z.array(z.string()).min(1),
  dimension: topic,
  public_topic: topic,
  finding: z.string().max(2000),
  inference: z.string().max(2000),
  relevance: z.string().max(1000),
  unknown: z.string().max(2000),
  question: z.string().max(1000),
  confidence: z.enum(["high", "medium", "low", "unknown"]),
  locator,
  quote: z.string().max(10000),
  status: z.literal("unverified_source_interpretation"),
});
const attempt = z.object({
  channel,
  status: z.string(),
  stage: z.string(),
  at: z.string(),
  provider: z.string().optional(),
  platform: z.string().optional(),
  access_mode: access.optional(),
  url: z.string().optional(),
  query: z.string().optional(),
  reason: z.string().optional(),
  elapsed_ms: z.number().optional(),
  count: z.number().optional(),
  evidence_id: z.string().optional(),
  rejected_subjects: z.number().optional(),
});
export const v2ResultSchema = z.object({
  version: z.literal("agent-v2.1"),
  rule_version: z.string(),
  run_id: z.string(),
  company_id: z.number().int().positive(),
  identity: z.object({
    company_id: z.number().int().positive(),
    legal_name: z.string().nullable(),
    brand: z.string(),
    aliases: z.array(z.string()),
    credit_code: z.string().nullable(),
    stock: z.object({ market: z.string(), code: z.string() }).nullable(),
    relationship: z.string(),
    match_status: z.string(),
    candidates: z.array(z.unknown()),
    job_scope: z.string(),
  }),
  status: z.enum(["completed", "partial"]),
  documents: z
    .array(
      z.object({
        id: z.string(),
        company_id: z.number().int().positive(),
        company_name: z.string(),
        job_id: z.null(),
        scope: z.literal("company"),
        channel,
        channels: z.array(channel),
        platform: z.string(),
        provider: z.string(),
        access_mode: access,
        url: z.string().url(),
        title: z.string().max(1000),
        published_at: z.string().nullable(),
        collected_at: z.string(),
        content_hash: z.string(),
        raw_hash: z.string().nullable(),
        raw_path: z.string().nullable(),
        entity_match: z.string(),
        report_period: z.string().nullable(),
        experience_period: z.string().nullable(),
        department: z.string().nullable(),
        role: z.string().nullable(),
        city: z.string().nullable(),
        employee_identity: z.string(),
        source_lineage: z.string(),
        dimensions: z.array(topic),
        fixture: z.boolean(),
        text_length: z.number(),
        physical_pages: z.number(),
        parser_version: z.string(),
        warnings: z.array(z.string()),
        procurement: z
          .object({
            stage: z.string(),
            buyer: z.string().nullable(),
            beneficiary: z.string().nullable(),
            amount_quote: z.string().nullable(),
            benefit_delivered: z.null(),
            per_employee_value: z.null(),
            limitation: z.string(),
          })
          .optional(),
      }),
    )
    .max(20),
  excerpts: z
    .array(
      z.object({
        id: z.string(),
        document_id: z.string(),
        company_id: z.number().int().positive(),
        title: z.string().max(1000),
        excerpt: z.string().min(1).max(10000),
        url: z.string().url(),
        published_at: z.string().nullable(),
        collected_at: z.string(),
        channel,
        access_mode: access,
        locator,
        dimensions: z.array(topic),
        content_hash: z.string(),
        fixture: z.boolean(),
      }),
    )
    .max(120),
  facts: z.array(fact).max(90),
  translations: z.array(translation).max(28),
  attempts: z.array(attempt).max(100),
  capabilities: z.array(
    z.object({
      platform: z.string(),
      label: z.string(),
      channel: z.string(),
      domain: z.string(),
      capability: z.string(),
      direct_status: z.string(),
      configured_api: z.boolean(),
      login_used: z.literal(false),
      reason: z.string(),
    }),
  ),
  gaps: z.array(
    z.object({
      topic: z.string(),
      status: z.literal("unknown"),
      reason: z.string(),
    }),
  ),
  followups: z
    .array(
      z.object({
        round: z.number(),
        topic: z.string(),
        target: z.string(),
        query: z.string(),
        channel: z.string(),
        reason: z.string(),
        budget: z.object({ queries: z.number(), hits: z.number() }),
        new_independent_sources: z.number(),
      }),
    )
    .max(2),
  reviews: z.array(
    z.object({
      claim_ids: z.array(z.string()),
      status: z.literal("unresolved"),
      rule_version: z.string(),
      kind: z.string(),
      reason: z.string(),
    }),
  ),
  ratios: z.array(
    z.object({
      metric: z.string(),
      value: z.string(),
      formula: z.string(),
      input_fact_ids: z.array(z.string()),
      period: z.string(),
      reporting_scope: z.string(),
      status: z.literal("derived_from_source_claims"),
    }),
  ),
  stop_reason: z.string(),
  reused_channels: z.array(z.string()),
  notes: z.array(z.string()),
  elapsed_ms: z.number(),
  independent_sources: z.number(),
  stored_fact_count: z.number(),
  stored_document_count: z.number(),
  model: z.object({ status: z.string(), reason: z.string() }),
});
export type V2Result = z.infer<typeof v2ResultSchema>;
